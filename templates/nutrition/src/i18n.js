export function setLanguage(lang) {
    if (!['en', 'my'].includes(lang)) lang = 'en';
    localStorage.setItem('nutriflow_lang', lang);
    document.documentElement.lang = lang;
    updateDOM();
}

export function getLanguage() {
    return localStorage.getItem('nutriflow_lang') || 'en';
}

export function updateDOM() {
    const lang = getLanguage();
    const t = translations[lang];
    if (!t) return;
    
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t[key]) {
            // Some keys might contain HTML, like hero.joined
            if (t[key].includes('<')) {
                el.innerHTML = t[key];
            } else {
                el.textContent = t[key];
            }
        }
    });
    
    // Update placeholders if they have a data-i18n-placeholder attribute
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (t[key]) {
            el.placeholder = t[key];
        }
    });
}

// Auto-initialize on load
document.addEventListener('DOMContentLoaded', () => {
    const lang = getLanguage();
    document.documentElement.lang = lang;
    updateDOM();
    
    // Sync UI language selector if it exists
    const langSelect = document.getElementById('lang-selector');
    if (langSelect) {
        langSelect.value = lang;
        langSelect.addEventListener('change', (e) => {
            setLanguage(e.target.value);
        });
    }
});
